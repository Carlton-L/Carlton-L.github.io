// Builds the layout for the Engine case study's "before" view: the first workflow screen, recreated
// on the made-up run (every step and wire on one board, no grouping), and the redesign's top level,
// for the before/after slider. Output: src/data/demos/engine/before.json (small; the page draws it).
// Prototype: docs/prototypes/engine-before.html (direction C, accepted 2026-11-14).
// Confirmed with Carlton (2026-11-14): the old screen was a dark board with no workstream grouping;
// it shows the made-up run's steps as they are (70 plus 4 filings), not the real run's about 160.
// Usage: node scripts/engine-run/build-before.mjs
import { writeFileSync } from 'node:fs';
import { G, KIND, LINKS_ALL, KBR, PARENT, CHAPTERS, REPORT_OUTLINE } from '../../src/data/demos/engine/smr-run.js';

const FILES = KBR.files;
const top = (id) => { let c = id; while (PARENT[c] && PARENT[c] !== 'report') c = PARENT[c]; return CHAPTERS[c] ? c : null; };
const ids = Object.keys(G).filter((id) => id !== '1');
const cat = (id) => (FILES[id] ? 'kb' : (KIND[G[id].type] || ['', ''])[1]);
const edges = LINKS_ALL.filter((l) => l[4] !== 'order').map((l) => [l[0], l[2]])
  .concat(Object.entries(KBR.needs || {}).flatMap(([r, fs]) => fs.map((f) => [f, r])))
  .filter(([a, b]) => ids.includes(a) && ids.includes(b));
const pred = {}; edges.forEach(([a, b]) => { (pred[b] = pred[b] || []).push(a); });

// layered by longest path, as the old screen drew it; Assemble and Publish last
const depth = {};
const dep = (id) => (depth[id] != null ? depth[id] : (depth[id] = Math.max(0, ...(pred[id] || []).map((p) => dep(p) + 1))));
ids.forEach(dep);
const mx = Math.max(...ids.filter((i) => i !== '105' && i !== '106').map((i) => depth[i]));
depth['105'] = mx + 1; depth['106'] = mx + 2;
const layers = []; ids.forEach((id) => { (layers[depth[id]] = layers[depth[id]] || []).push(id); });

const W = 760, H = 380, PADX = 18, PADY = 16, NODE_W = 52;
const pos = {};
const avg = (id) => { const ps = (pred[id] || []).filter((p) => pos[p]); return ps.length ? ps.reduce((a, p) => a + pos[p][1], 0) / ps.length : 0; };
layers.forEach((L, i) => {
  if (i) L.sort((a, b) => avg(a) - avg(b));
  L.forEach((id, k) => { pos[id] = [Math.round(PADX + (i * (W - 2 * PADX - NODE_W)) / (layers.length - 1)), Math.round(PADY + ((k + 0.5) * (H - 2 * PADY)) / L.length)]; });
});
const nodes = ids.map((id) => { const t = (FILES[id] ? FILES[id].title : G[id].title); return [id, t.length > 18 ? t.slice(0, 17) + '…' : t, cat(id), ...pos[id]]; });

// the redesign's top level: five workstreams, then the report
const steps = (ws) => ids.filter((i) => !FILES[i] && top(i) === ws).length;
const after = {
  boxes: [['c_ground', 40, 150], ['c_eng', 230, 40], ['c_sci', 230, 150], ['c_biz', 230, 260], ['c_syn', 430, 150]]
    .map(([ws, x, y]) => [CHAPTERS[ws].title, steps(ws), x, y, 120, 70]),
  wires: [[0, 1], [0, 2], [0, 3], [1, 4], [2, 4], [3, 4]],
  report: [610, 90, 120, 190],
  outline: REPORT_OUTLINE.map(([t]) => (t.length > 22 ? t.slice(0, 21) + '…' : t)),
};
const out = { _meta: { synthetic: true, demo: 'engBefore', note: 'Made-up run; generated by scripts/engine-run/build-before.mjs' }, w: W, h: H, nodeW: NODE_W, nodes, edges, after };
const path = new URL('../../src/data/demos/engine/before.json', import.meta.url).pathname;
writeFileSync(path, JSON.stringify(out));
console.log(path + ':', nodes.length, 'nodes,', edges.length, 'wires,', JSON.stringify(out).length, 'bytes');
